SET ECHO OFF
SET VERIFY OFF
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK
ALTER SESSION SET CONTAINER = FREEPDB1;
-- Ejecutar una sola vez como SYSDBA. Si FUEL_APP existe, revisar su estado.
ACCEPT clave_app CHAR PROMPT 'Nueva clave para FUEL_APP (letras y numeros, minimo 16): ' HIDE
CREATE USER FUEL_APP IDENTIFIED BY "&clave_app"
  DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 100M ON USERS;
UNDEFINE clave_app
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE TRIGGER, CREATE SEQUENCE TO FUEL_APP;
PROMPT Usuario creado. Conectarse como FUEL_APP para ejecutar 01_schema.sql.
EXIT SUCCESS
