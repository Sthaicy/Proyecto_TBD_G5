CREATE OR REPLACE TRIGGER trg_tx_contexto
BEFORE INSERT OR UPDATE ON transaccion
FOR EACH ROW
BEGIN
  IF :NEW.id_combustible IS NULL THEN
    SELECT id_combustible INTO :NEW.id_combustible FROM surtidor WHERE id_surtidor = :NEW.id_surtidor;
  END IF;
  :NEW.ref_carga := NULL;
  :NEW.ref_bidon := NULL;
  IF :NEW.tipo_transaccion = 'CARGA_VEHICULAR' THEN
    :NEW.ref_carga := :NEW.id_transaccion;
  ELSIF :NEW.tipo_transaccion = 'COMPRA_BIDON' THEN
    :NEW.ref_bidon := :NEW.id_transaccion;
  END IF;
END;
