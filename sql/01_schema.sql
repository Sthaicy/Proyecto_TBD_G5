CREATE OR REPLACE TRIGGER trg_det_vigencia
BEFORE INSERT OR UPDATE ON detalle_transaccion
FOR EACH ROW
DECLARE
  v_fecha TIMESTAMP;
  v_desde DATE;
  v_hasta DATE;
BEGIN
  IF :NEW.id_transaccion IS NULL OR :NEW.id_precio IS NULL THEN RETURN; END IF;
  SELECT fecha_hora INTO v_fecha FROM transaccion WHERE id_transaccion = :NEW.id_transaccion;
  SELECT vigente_desde, vigente_hasta INTO v_desde, v_hasta FROM precio_combustible WHERE id_precio = :NEW.id_precio;
  IF v_fecha < CAST(v_desde AS TIMESTAMP) OR (v_hasta IS NOT NULL AND v_fecha >= CAST(v_hasta AS TIMESTAMP)) THEN
    RAISE_APPLICATION_ERROR(-20010, 'El precio no esta vigente en la fecha de la transaccion.');
  END IF;
END;
/

-- Protege el historial: para cambiar precios se crea una nueva version.
CREATE OR REPLACE TRIGGER trg_precio_historial
BEFORE UPDATE OF vigente_desde, vigente_hasta ON precio_combustible
FOR EACH ROW
DECLARE v_total NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_total FROM detalle_transaccion d JOIN transaccion t ON t.id_transaccion = d.id_transaccion
    WHERE d.id_precio = :OLD.id_precio AND (t.fecha_hora < CAST(:NEW.vigente_desde AS TIMESTAMP)
      OR (:NEW.vigente_hasta IS NOT NULL AND t.fecha_hora >= CAST(:NEW.vigente_hasta AS TIMESTAMP)));
  IF v_total > 0 THEN RAISE_APPLICATION_ERROR(-20011, 'La nueva vigencia excluye ventas historicas.'); END IF;
END;
/
