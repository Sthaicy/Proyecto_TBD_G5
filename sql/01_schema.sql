-- Comparacion fisica a la misma fecha de corte, nunca contra movimientos posteriores.
CREATE OR REPLACE VIEW v_conciliacion_tanque AS
SELECT b.id_tanque, b.unidad, b.fecha_ultima_medicion, b.ultima_medicion,
  b.stock_inicial
  + NVL((SELECT SUM(r.cantidad) FROM recepcion_combustible r WHERE r.id_tanque=b.id_tanque
      AND r.fecha_hora>=ta.fecha_inicio AND r.fecha_hora<=b.fecha_ultima_medicion),0)
  - NVL((SELECT SUM(d.cantidad) FROM detalle_transaccion d JOIN transaccion t ON t.id_transaccion=d.id_transaccion
      JOIN surtidor su ON su.id_surtidor=t.id_surtidor WHERE su.id_tanque=b.id_tanque AND t.estado='APROBADA'
      AND t.fecha_hora>=ta.fecha_inicio AND t.fecha_hora<=b.fecha_ultima_medicion),0)
  + NVL((SELECT SUM(a.cantidad) FROM ajuste_inventario a WHERE a.id_tanque=b.id_tanque
      AND a.fecha_hora>=ta.fecha_inicio AND a.fecha_hora<=b.fecha_ultima_medicion),0)
  - b.ultima_medicion AS diferencia
FROM v_balance_tanque b JOIN tanque ta ON ta.id_tanque=b.id_tanque
WHERE b.fecha_ultima_medicion IS NOT NULL;

-- Cambiar la asignacion de un surtidor con ventas alteraria el inventario historico.
CREATE OR REPLACE TRIGGER trg_surtidor_historial
BEFORE UPDATE OF id_tanque, id_estacion, id_combustible ON surtidor
FOR EACH ROW
DECLARE v_total NUMBER;
BEGIN
  IF :NEW.id_tanque<>:OLD.id_tanque OR :NEW.id_estacion<>:OLD.id_estacion OR :NEW.id_combustible<>:OLD.id_combustible THEN
    SELECT COUNT(*) INTO v_total FROM transaccion WHERE id_surtidor=:OLD.id_surtidor;
    IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20014,'Crear otro surtidor para conservar el historial.'); END IF;
  END IF;
END;
/
CREATE OR REPLACE TRIGGER trg_tanque_historial
BEFORE UPDATE OF stock_inicial, fecha_inicio, id_estacion, id_combustible, capacidad ON tanque
FOR EACH ROW
DECLARE v_total NUMBER; v_max NUMBER;
BEGIN
  SELECT MAX(cantidad) INTO v_max FROM medicion_tanque WHERE id_tanque=:OLD.id_tanque;
  IF :NEW.capacidad < v_max THEN RAISE_APPLICATION_ERROR(-20015,'La capacidad no puede ser menor que una medicion registrada.'); END IF;
  IF :NEW.stock_inicial<>:OLD.stock_inicial OR :NEW.fecha_inicio<>:OLD.fecha_inicio
      OR :NEW.id_estacion<>:OLD.id_estacion OR :NEW.id_combustible<>:OLD.id_combustible THEN
    SELECT (SELECT COUNT(*) FROM recepcion_combustible WHERE id_tanque=:OLD.id_tanque)
      +(SELECT COUNT(*) FROM medicion_tanque WHERE id_tanque=:OLD.id_tanque)
      +(SELECT COUNT(*) FROM ajuste_inventario WHERE id_tanque=:OLD.id_tanque)
      +(SELECT COUNT(*) FROM surtidor su JOIN transaccion t ON t.id_surtidor=su.id_surtidor WHERE su.id_tanque=:OLD.id_tanque)
      INTO v_total FROM dual;
    IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20016,'Usar ajustes documentados o un tanque nuevo para conservar el historial.'); END IF;
  END IF;
END;
/

