-- Unidades de capacidad, medicion y ajuste: las del combustible del tanque.
CREATE OR REPLACE VIEW v_balance_tanque AS
SELECT q.*
FROM (
  SELECT ta.id_tanque, ta.id_estacion, ta.id_combustible, ta.codigo, um.simbolo AS unidad,
    ta.stock_inicial,
    NVL((SELECT SUM(r.cantidad) FROM recepcion_combustible r WHERE r.id_tanque=ta.id_tanque AND r.fecha_hora>=ta.fecha_inicio),0) AS recibido,
    NVL((SELECT SUM(d.cantidad) FROM detalle_transaccion d JOIN transaccion t ON t.id_transaccion=d.id_transaccion JOIN surtidor su ON su.id_surtidor=t.id_surtidor
      WHERE su.id_tanque=ta.id_tanque AND t.estado='APROBADA' AND t.fecha_hora>=ta.fecha_inicio),0) AS vendido,
    NVL((SELECT SUM(a.cantidad) FROM ajuste_inventario a WHERE a.id_tanque=ta.id_tanque AND a.fecha_hora>=ta.fecha_inicio),0) AS ajustes,
    ta.stock_inicial
    + NVL((SELECT SUM(r.cantidad) FROM recepcion_combustible r WHERE r.id_tanque=ta.id_tanque AND r.fecha_hora>=ta.fecha_inicio),0)
    - NVL((SELECT SUM(d.cantidad) FROM detalle_transaccion d JOIN transaccion t ON t.id_transaccion=d.id_transaccion JOIN surtidor su ON su.id_surtidor=t.id_surtidor
      WHERE su.id_tanque=ta.id_tanque AND t.estado='APROBADA' AND t.fecha_hora>=ta.fecha_inicio),0)
    + NVL((SELECT SUM(a.cantidad) FROM ajuste_inventario a WHERE a.id_tanque=ta.id_tanque AND a.fecha_hora>=ta.fecha_inicio),0) AS saldo_teorico,
    (SELECT MAX(m.cantidad) KEEP (DENSE_RANK LAST ORDER BY m.fecha_hora) FROM medicion_tanque m WHERE m.id_tanque=ta.id_tanque) AS ultima_medicion,
    (SELECT MAX(m.fecha_hora) FROM medicion_tanque m WHERE m.id_tanque=ta.id_tanque) AS fecha_ultima_medicion
  FROM tanque ta JOIN combustible c ON c.id_combustible=ta.id_combustible JOIN unidad_medida um ON um.id_unidad=c.id_unidad
) q;

