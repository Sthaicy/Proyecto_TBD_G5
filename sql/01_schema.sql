CREATE TABLE transaccion (
  id_combustible NUMBER NOT NULL,
  ref_carga NUMBER,
  ref_bidon NUMBER,
  id_transaccion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000000) CONSTRAINT pk_transaccion PRIMARY KEY,
  id_surtidor NUMBER NOT NULL,
  id_persona NUMBER NOT NULL,
  id_usuario NUMBER NOT NULL,
  tipo_transaccion VARCHAR2(20) NOT NULL,
  fecha_hora TIMESTAMP NOT NULL,
  estado VARCHAR2(10) NOT NULL,
  CONSTRAINT uk_tx_comb UNIQUE (id_transaccion, id_combustible),
  CONSTRAINT uk_tx_tipo UNIQUE (id_transaccion, tipo_transaccion),
  CONSTRAINT fk_tx_surt_comb FOREIGN KEY (id_surtidor, id_combustible) REFERENCES surtidor(id_surtidor, id_combustible),
  CONSTRAINT ck_tx_tipo CHECK (tipo_transaccion IN ('CARGA_VEHICULAR', 'COMPRA_BIDON')),
  CONSTRAINT ck_tx_subtipo CHECK (
    (tipo_transaccion = 'CARGA_VEHICULAR' AND ref_carga IS NOT NULL AND ref_carga = id_transaccion AND ref_bidon IS NULL)
    OR (tipo_transaccion = 'COMPRA_BIDON' AND ref_bidon IS NOT NULL AND ref_bidon = id_transaccion AND ref_carga IS NULL)),
  CONSTRAINT fk_tx_persona FOREIGN KEY (id_persona) REFERENCES persona(id_persona),
  CONSTRAINT fk_tx_surtidor FOREIGN KEY (id_surtidor) REFERENCES surtidor(id_surtidor),
  CONSTRAINT fk_tx_usuario FOREIGN KEY (id_usuario) REFERENCES usuario_sistema(id_usuario)
);
CREATE INDEX ix_tx_persona_fecha ON transaccion(id_persona, fecha_hora);
CREATE INDEX ix_tx_surtidor_fecha ON transaccion(id_surtidor, fecha_hora);

